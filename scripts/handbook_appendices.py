"""Generate a handbook's glossary and answers appendices from its chapters.

    python3 scripts/handbook_appendices.py cloud-identity D E

Reads every written chapter's key terms (<dl class="terms">) and quiz (<ol class="quiz">) and writes
content/handbooks/<key>/appendix-<d>.html (glossary) and appendix-<e>.html (answers). Rerun it after editing a
chapter's terms or questions, then rebuild; the generated files say so at the top.
"""
import html
import re
import runpy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content" / "handbooks"


def strip(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def chapters(book):
    for part in book["parts"]:
        for num, slug, title, *_ in part["chapters"]:
            path = CONTENT / book["key"] / f"{num:02d}-{slug}.html"
            if path.exists():
                yield num, title, path.read_text(encoding="utf-8")


def opener(letter, title, promise):
    return (f'<!-- Generated by scripts/handbook_appendices.py from the chapters; do not edit by hand. -->\n'
            f'<header class="opener">\n  <p class="eyebrow">Appendix</p>\n  <p class="chno">{letter}</p>\n'
            f'  <h1>{title}</h1>\n  <p class="promise">{promise}</p>\n</header>\n')


def glossary(book, letter, title):
    terms = {}
    for num, _, body in chapters(book):
        m = re.search(r'<dl class="terms">(.*?)</dl>', body, re.S)
        for dt, dd in re.findall(r"<dt>(.*?)</dt>\s*<dd>(.*?)</dd>", m.group(1) if m else "", re.S):
            key = re.sub(r"^[^0-9a-z]+", "", strip(dt).lower())
            terms.setdefault(key, dict(dt=dt, defs=[]))["defs"].append((dd, num))
    count = len({n for e in terms.values() for _, n in e["defs"]})
    out = [opener(letter, title, f"Every key term from the {count} chapters, in alphabetical order, with the "
                  "chapter that explains it. A term defined in more than one chapter has one line per chapter.")]
    current = None
    for key in sorted(terms):
        first = key[0].upper() if key[0].isalpha() else "#"
        if first != current:
            if current:
                out.append("</dl>\n")
            current = first
            out.append(f'<h2 class="sec" id="gl-{first.lower() if first != "#" else "num"}">'
                       f'<span class="n">{first}</span></h2>\n<dl class="terms glossary">')
        e = terms[key]
        dds = "".join(f'<dd>{dd} <span class="gl-ref">(<a href="#ch{n}">Chapter {n}</a>)</span></dd>'
                      for dd, n in e["defs"])
        out.append(f'  <dt>{e["dt"]}</dt>{dds}')
    out.append("</dl>\n")
    return "\n".join(out)


def answers(book, letter, title):
    out = [opener(letter, title, "Worked answers to every “check your understanding” question, chapter by "
                  "chapter. Try each question before you read its answer: the effort of recalling is what makes "
                  "it stick.")]
    for num, ch_title, body in chapters(book):
        m = re.search(r'<ol class="quiz">(.*?)</ol>\s*<h3>', body, re.S)
        out.append(f'<h2 class="sec" id="ans{num}"><span class="n">{num}</span>{ch_title}</h2>')
        out.append('<ol class="answers">')
        for q, a in re.findall(r"<li>\s*<p>(.*?)</p>\s*<details><summary>.*?</summary>(.*?)</details>\s*</li>",
                               m.group(1), re.S):
            out.append(f'  <li><p class="q">{q.strip()}</p>{a.strip()}</li>')
        out.append(f'</ol>\n<p class="back"><a href="#ch{num}">Back to Chapter {num}</a></p>\n')
    return "\n".join(out)


def nav(book, letter):
    order = [a for a, _, _ in book["appendices"]]
    titles = {a: t for a, t, _ in book["appendices"]}
    i = order.index(letter)
    links = []
    if i > 0:
        links.append(f'  <div><span>Previous</span><a href="#app{order[i - 1]}">Appendix {order[i - 1]} · {titles[order[i - 1]]}</a></div>')
    if i + 1 < len(order):
        links.append(f'  <div><span>Next</span><a href="#app{order[i + 1]}">Appendix {order[i + 1]} · {titles[order[i + 1]]}</a></div>')
    return '\n<nav class="next" aria-label="Chapters">\n' + "\n".join(links) + "\n</nav>\n"


def main(key, gl_letter, ans_letter):
    book = runpy.run_path(str(CONTENT / key / "book.py"))["BOOK"]
    titles = {a: t for a, t, _ in book["appendices"]}
    for letter, make in ((gl_letter, glossary), (ans_letter, answers)):
        path = CONTENT / key / f"appendix-{letter.lower()}.html"
        path.write_text(make(book, letter, titles[letter]) + nav(book, letter), encoding="utf-8")
        print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main(*sys.argv[1:4])
